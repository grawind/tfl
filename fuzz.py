import random
import re

def random_word(n):
    s = ""
    alphabet = "abc"
    for i in range(n):
        s = s + alphabet[random.randint(0, 2)]
    return s

def check_word(word):
    pattern = r'^(aaa|bbb|cc|ab(ccc)*|aa)*(aa|bbb|aab(cc)*|bbbb)*(aaa|bbb|cc|ab(ccc)*|aa)*$'
    return bool(re.fullmatch(pattern, word))

