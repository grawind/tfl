def checkNFA(word, state=0):
    if len(word) == 0:
        if state in fin_NFA:
            return True
        else:
            for i in NFA[state][3]:
                if checkNFA(word, i):
                    return True
        return False

    letter = word[0]

    for i in NFA[state][ord(letter) - 97]:
        if checkNFA(word[1:], i):
            return True

    for i in NFA[state][3]:
        if checkNFA(word, i):
            return True

    return False

